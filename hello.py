# ============ 我的第一个 Python 程序 ============

# 1. print() 在屏幕上显示文字
print("Hello, World!")
print("你好，Python！")

# 2. 变量：给数据起个名字，存进"盒子"
name = "cairobaby"
site = "https://cairobaby.github.io"
print("我是", name)
print("我的网站：", site)

# 3. 数字与运算
a = 7
b = 3
print("7 + 3 =", a + b)
print("7 - 3 =", a - b)
print("7 x 3 =", a * b)
print("7 / 3 =", a / b)
print("7 除以 3 的余数 =", a % b)

# 4. input() 让程序和你对话（运行到这里会等你输入）
your_name = input("请输入你的名字：")
print("你好，", your_name, "！很高兴认识你。")

# 5. 字符串拼接
message = "Python" + " 很好玩！"
print(message)
